[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$RepoRoot = Split-Path -Parent $PSScriptRoot
$ComponentsRoot = Join-Path $RepoRoot 'Components'
$RequirementsRoot = Join-Path $RepoRoot 'Requirements'
$DocsRoot = Join-Path $RepoRoot 'docs'

if (-not (Test-Path -LiteralPath $ComponentsRoot -PathType Container)) { throw "Missing Components folder: $ComponentsRoot" }
if (-not (Test-Path -LiteralPath $RequirementsRoot -PathType Container)) { throw "Missing Requirements folder: $RequirementsRoot" }
if (-not (Test-Path -LiteralPath $DocsRoot -PathType Container)) { New-Item -ItemType Directory -Path $DocsRoot | Out-Null }

function Write-Utf8NoBom([string]$Path, [string[]]$Lines) {
    $Text = ($Lines -join "`n") + "`n"
    [System.IO.File]::WriteAllText($Path, $Text, [System.Text.UTF8Encoding]::new($false))
}
function Get-YamlValue([string]$YamlPath, [string]$Key, [string]$Fallback) {
    if (Test-Path -LiteralPath $YamlPath -PathType Leaf) {
        $match = Get-Content -LiteralPath $YamlPath -Encoding UTF8 | Where-Object { $_ -match "^\s*$([Regex]::Escape($Key))\s*:\s*(.+?)\s*$" } | Select-Object -First 1
        if ($match -and $match -match "^\s*$([Regex]::Escape($Key))\s*:\s*(.+?)\s*$") {
            $value = $Matches[1].Trim().Trim('"').Trim("'")
            if ($value) { return $value }
        }
    }
    return $Fallback
}
function Get-ReadmeDescription([string]$Path) {
    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) { return 'No description supplied.' }
    $parts = New-Object System.Collections.Generic.List[string]
    foreach ($raw in Get-Content -LiteralPath $Path -Encoding UTF8) {
        $line=$raw.Trim()
        if (-not $line) { if($parts.Count){break}; continue }
        if ($line -match '^(#|---|\|)' -or $line -match '^[-*+]\s') { continue }
        $parts.Add($line)
        if (($parts -join ' ').Length -ge 220) { break }
    }
    if (-not $parts.Count) { return 'See the component README for details.' }
    $text=(($parts -join ' ') -replace '\s+',' ').Trim()
    if($text.Length -gt 280){$text=$text.Substring(0,277).TrimEnd()+'...'}
    return $text
}

$components = New-Object System.Collections.Generic.List[object]
foreach ($dir in Get-ChildItem -LiteralPath $ComponentsRoot -Directory | Sort-Object Name) {
    $yaml = Join-Path $dir.FullName 'component.yaml'
    $readme = Join-Path $dir.FullName 'README.md'
    $name = Get-YamlValue $yaml 'name' ($dir.Name -replace '[-_]',' ')
    $version = Get-YamlValue $yaml 'version' 'UNSET'
    $source = Get-YamlValue $yaml 'source_url' 'UNSET'
    $license = Get-YamlValue $yaml 'license' 'UNSET'
    $verify = Get-YamlValue $yaml 'verification_command' 'UNSET'
    $target = Get-YamlValue $yaml 'target_directory' ("tools/"+$dir.Name.ToLowerInvariant())
    $description = Get-ReadmeDescription $readme
    $components.Add([pscustomobject]@{Name=$name;Version=$version;Source=$source;License=$license;Verify=$verify;Target=$target;Description=$description;Folder=$dir.Name})
}

$componentLines = @('# Components', '', 'Generated from `Components/*/component.yaml` and each component README. Do not edit this file by hand.', '', '| Component | Purpose | Version | License | Verification |', '|---|---|---|---|---|')
if(-not $components.Count){$componentLines += '| No components found | Add folders under `Components/` | | | |'}
foreach($c in $components){
    $desc=$c.Description -replace '\|','\|'; $verify=$c.Verify -replace '\|','\|'
    $componentLines += "| $($c.Name) | $desc | $($c.Version) | $($c.License) | ``$verify`` |"
}
$componentLines += @('', '## Component details')
foreach($c in $components){
    $componentLines += @('', "### $($c.Name)", '', $c.Description, '', "- **Folder:** ``Components/$($c.Folder)/``", "- **Target:** ``$($c.Target)``", "- **Version:** $($c.Version)", "- **Source:** $($c.Source)", "- **License:** $($c.License)", "- **Verification:** ``$($c.Verify)``")
}
Write-Utf8NoBom (Join-Path $DocsRoot 'components.md') $componentLines

$profiles = Get-ChildItem -LiteralPath $RequirementsRoot -File -Filter 'requirements-*.txt' | Sort-Object Name
$profileLines = @('# Installation Profiles', '', 'Generated from `Requirements/requirements-*.txt`. Do not edit this file by hand.', '')
foreach($file in $profiles){
    $slug=$file.BaseName.Substring('requirements-'.Length)
    $display=(Get-Culture).TextInfo.ToTitleCase(($slug -replace '[-_]',' '))
    $packages = Get-Content -LiteralPath $file.FullName -Encoding UTF8 | ForEach-Object { ($_ -split '#',2)[0].Trim() } | Where-Object { $_ }
    $profileLines += @("## $display", '', "- **Requirements file:** ``Requirements/$($file.Name)``", "- **Package entries:** $($packages.Count)", '')
    if($packages.Count){ $profileLines += ($packages | ForEach-Object { "- ``$_``" }) } else { $profileLines += '_No package entries yet._' }
    $profileLines += ''
}
Write-Utf8NoBom (Join-Path $DocsRoot 'profiles.md') $profileLines

$verificationLines = @('# Verification', '', 'Generated from component metadata. Do not edit this file by hand.', '', 'Run only checks required by the installed profile.', '')
$validChecks=0
foreach($c in $components){
    if($c.Verify -and $c.Verify -ne 'UNSET'){$verificationLines += "- **$($c.Name):** ``$($c.Verify)``"; $validChecks++}
}
if(-not $validChecks){$verificationLines += '_No verification commands have been configured yet._'}
$verificationLines += @('', '## Python dependency integrity', '', 'If Python packages are installed, run `python -m pip check`.')
Write-Utf8NoBom (Join-Path $DocsRoot 'verification.md') $verificationLines

$index=@("# Emmre's Agent Environment",'',"A portable, folder-based Windows environment for Emmre's agent tools.",'','## Start here','- [Installation](installation.md)','- [Components](components.md)','- [Profiles](profiles.md)','- [Verification](verification.md)','- [Updating](updating.md)','- [Troubleshooting](troubleshooting.md)','- [Security](security.md)','- [Licensing](licensing.md)','','## Inventory',"- **Documented components:** $($components.Count)","- **Requirements profiles:** $($profiles.Count)",'','## Components')
foreach($c in $components){$index += "- $($c.Name)"}
$index += @('','## Important','This site documents the environment. Agent Builder can use these pages as knowledge, but it does not automatically execute locally installed components.')
Write-Utf8NoBom (Join-Path $DocsRoot 'index.md') $index

Write-Host "Updated index.md, components.md, profiles.md, and verification.md."
Write-Host "Found $($components.Count) component(s) and $($profiles.Count) requirements profile(s)."
